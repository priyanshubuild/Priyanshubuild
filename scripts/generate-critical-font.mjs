import { writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
const root = fileURLToPath(new URL("../", import.meta.url));
const source = `${root}public/fonts/geist-pixel-square-v1.woff2`;
await mkdir(`${root}public/fonts`, { recursive: true });
await promisify(execFile)("python3", [
  "-m", "fontTools.subset", source,
  "--unicodes=U+0000-007F,U+2000-206F",
  "--flavor=woff2",
  `--output-file=${root}public/fonts/geist-pixel-square-latin-v1.woff2`,
]);
await writeFile(
  `${root}src/app/geist-pixel.css`,
  `/* Generated by scripts/generate-critical-font.mjs. The critical subset preserves the original glyphs; the complete font covers other characters. License: public/font-licenses/Geist-OFL.txt. */\n@font-face{font-family:GeistPixelSquare;font-style:normal;font-weight:500;font-display:swap;src:url("/fonts/geist-pixel-square-latin-v1.woff2") format("woff2");unicode-range:U+0000-007F,U+2000-206F;}\n@font-face{font-family:GeistPixelSquare;font-style:normal;font-weight:500;font-display:swap;src:url("/fonts/geist-pixel-square-v1.woff2") format("woff2");unicode-range:U+0080-1FFF,U+2070-10FFFF;}\n:root{--font-geist-pixel-square:GeistPixelSquare;}\n`,
);
console.log(
  "Regenerated the critical subset from the committed original font. Its license remains in public/font-licenses.",
);
