"""Count current source lines in public repositories without executing their code."""
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import ssl
import subprocess
import sys
import tempfile
import urllib.error
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone

CLOC_URL = "https://raw.githubusercontent.com/AlDanial/cloc/v2.10/cloc"
CLOC_SHA256 = "bf59272455172108072a0a106379f7509fd4349bdcfd85203bac038ccd286d83"
EXCLUDED_DIRS = {"node_modules", ".git", ".next", "dist", "build", "out", "coverage", "vendor", "venv", ".venv", "__pycache__", ".ipynb_checkpoints", "bower_components", "target"}
EXCLUDED_EXTENSIONS = {".json", ".csv", ".tsv", ".svg", ".md", ".mdx", ".yml", ".yaml", ".toml", ".lock", ".map", ".pdf", ".png", ".jpg", ".jpeg", ".gif", ".ico", ".woff", ".woff2", ".ttf", ".mp4", ".webm", ".zip"}
GENERATED = re.compile(r"(?:tailwindcss\s+v\d|bootstrap\s+v\d|jquery\s+v\d)|^\s*(?://|#|/\*+|\*|<!--).*?(?:auto[- ]generated|automatically generated|do not edit|generated by)", re.I | re.M)
CAFILE = "/etc/ssl/cert.pem" if Path("/etc/ssl/cert.pem").exists() else None
CONTEXT = ssl.create_default_context(cafile=CAFILE)

def download(url, authenticated=False, limit=32 * 1024 * 1024):
    headers = {"User-Agent": "priyanshu-public-source-counter"}
    if authenticated:
        if not url.startswith("https://api.github.com/"):
            raise ValueError("Credentials may only be sent to the GitHub API")
        headers["Accept"] = "application/vnd.github+json"
        if os.environ.get("GITHUB_TOKEN"):
            headers["Authorization"] = "Bearer " + os.environ["GITHUB_TOKEN"]
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), context=CONTEXT, timeout=45) as response:
        body = response.read(limit + 1)
        if len(body) > limit:
            raise ValueError("Source download exceeds the safety limit")
        return body

def github(path):
    return json.loads(download("https://api.github.com" + path, authenticated=True))

def repositories():
    result = {}
    for page in range(1, 21):
        rows = github(f"/users/priyanshubuild/repos?type=owner&per_page=100&page={page}")
        if not isinstance(rows, list):
            raise ValueError("Invalid repository list")
        for row in rows:
            if row.get("private") is not False or row.get("fork") is not False:
                continue
            name = row.get("full_name", "")
            if not re.fullmatch(r"priyanshubuild/[\w.-]+", name, re.I):
                raise ValueError("Invalid public repository")
            result[name.lower()] = row
        if len(rows) < 100:
            return list(result.values())
    raise ValueError("Incomplete repository pagination")

def fetch_sources(repo_name, sha, tree, destination, extensions):
    if tree.get("truncated") is not False or not isinstance(tree.get("tree"), list):
        raise ValueError("Incomplete source tree")
    files = []
    for item in tree["tree"]:
        if item.get("type") != "blob" or item.get("mode") not in {"100644", "100755"}:
            continue
        relative = PurePosixPath(item["path"])
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError("Unsafe source path")
        suffix = relative.suffix.lower()
        if any(part in EXCLUDED_DIRS for part in relative.parts) or suffix in EXCLUDED_EXTENSIONS or re.search(r"\.min\.(?:js|css)$", relative.name):
            continue
        if suffix.lstrip(".") not in extensions and relative.name.lower() not in extensions:
            continue
        if item.get("size", 0) > 5 * 1024 * 1024:
            raise ValueError("Source file exceeds the safety limit")
        files.append(relative)
    def fetch_one(relative):
        content = download(f"https://raw.githubusercontent.com/{repo_name}/{sha}/{urllib.parse.quote(str(relative), safe='/')}", limit=5 * 1024 * 1024)
        if b"\0" in content:
            return
        text = content.decode("utf-8", errors="replace")
        if GENERATED.search(text[:2048]):
            return
        target = destination / str(relative)
        if relative.suffix.lower() == ".ipynb":
            notebook = json.loads(text)
            language = notebook.get("metadata", {}).get("language_info", {}).get("name", "python").lower()
            extension = {"python": ".py", "javascript": ".js", "typescript": ".ts", "r": ".r", "julia": ".jl"}.get(language)
            if not extension:
                raise ValueError("Unsupported notebook code language")
            cells = [cell.get("source", []) for cell in notebook.get("cells", []) if cell.get("cell_type") == "code"]
            text = "\n\n".join("".join(cell) if isinstance(cell, list) else cell for cell in cells)
            target = target.with_name(target.name + ".source" + extension)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    with ThreadPoolExecutor(max_workers=6) as workers:
        list(workers.map(fetch_one, files))

def main():
    output = Path(sys.argv[1])
    totals = {}
    by_repository = []
    with tempfile.TemporaryDirectory(prefix="portfolio-source-lines-") as temporary:
        work = Path(temporary)
        cloc = work / "cloc.pl"
        binary = download(CLOC_URL)
        if hashlib.sha256(binary).hexdigest() != CLOC_SHA256:
            raise ValueError("The official cloc download failed its pinned checksum")
        cloc.write_bytes(binary)
        supported = subprocess.run(["perl", str(cloc), "--show-ext"], capture_output=True, text=True, check=True).stdout
        extensions = {line.split()[0].lower() for line in supported.splitlines()[2:] if line.strip()}
        extensions.update({"makefile", "dockerfile"})
        for index, repo in enumerate(repositories()):
            name = repo["full_name"]
            try:
                head = github(f"/repos/{name}/commits/{urllib.parse.quote(repo['default_branch'], safe='')}")
            except urllib.error.HTTPError as error:
                if error.code == 409:
                    by_repository.append({"repository": name, "commit": None, "lines": {}})
                    continue
                raise
            sha = head.get("sha", "")
            if not re.fullmatch(r"[a-f0-9]{40}", sha):
                raise ValueError("Invalid source commit")
            source = work / str(index)
            source.mkdir()
            tree_sha = head.get("commit", {}).get("tree", {}).get("sha", "")
            if not re.fullmatch(r"[a-f0-9]{40}", tree_sha):
                raise ValueError("Invalid source tree")
            fetch_sources(name, sha, github(f"/repos/{name}/git/trees/{tree_sha}?recursive=1"), source, extensions)
            environment = {key: value for key, value in os.environ.items() if key != "GITHUB_TOKEN"}
            result = subprocess.run(["perl", str(cloc), "--json", "--quiet", "--skip-uniqueness", "--no-autogen", "--timeout=30", str(source)], capture_output=True, text=True, check=True, timeout=60, env=environment)
            report = json.loads(result.stdout or "{}")
            lines = {}
            for language, metrics in report.items():
                if language in {"header", "SUM", "Text", "JSON", "Markdown", "YAML", "SVG", "TOML", "CSV"}:
                    continue
                count = metrics["code"]
                if not isinstance(count, int) or count < 0:
                    raise ValueError("Invalid source-line count")
                if count:
                    language = {"JSX": "JavaScript", "TSX": "TypeScript"}.get(language, language)
                    lines[language] = lines.get(language, 0) + count
                    totals[language] = totals.get(language, 0) + count
            by_repository.append({"repository": name, "commit": sha, "lines": lines})
            print(f"Counted source lines: {name}", file=sys.stderr)
    if not totals or sum(totals.values()) <= 0:
        raise ValueError("No recognized source lines; preserving the previous snapshot")
    data = {"lines": dict(sorted(totals.items(), key=lambda row: (-row[1], row[0]))), "repositories": by_repository, "fetchedAt": datetime.now(timezone.utc).isoformat(), "counter": "cloc 2.10", "scope": "public-non-fork-default-branches"}
    output.write_text(json.dumps(data, indent=2) + "\n")

if __name__ == "__main__":
    main()
